#!/usr/bin/env python3
"""Rebuild the compiled localized-string fixtures for the cross-check sample.

Writes STRINGS/Fallout4_en.{STRINGS,DLSTRINGS,ILSTRINGS} exactly per the byte
format documented in ghidra-dump/localized-string-file-format.md:

    offset  size  field
    0x00    4     u32 numStrings
    0x04    4     u32 dataSize
    0x08    8*N   rows { u32 stringID; u32 offset; }   (N == numStrings)
    0x08+8N  D    data block (D == dataSize)

invariant: fileSize == 8 + 8*numStrings + dataSize; rows sorted ascending by
stringID; .STRINGS records are NUL-terminated text, .DL/.ILSTRINGS records
are u32 len + text where len INCLUDES the trailing NUL.

The committed binaries were generated by this script; re-run it to rebuild
them (the TextExport.txt / supplemental inputs in ../input/ stay hand-edited
as the source of truth).

The ID set is deliberate:

    .STRINGS    0x12, 0x13            <- TextExport Topic/Response Text
    .DLSTRINGS  0x10, 0x36            <- TextExport Quest Stage Log Entry/Description
    .ILSTRINGS  0x126c5, 0x126c6      <- supplemental 000126c5.txt, and the
                                         Book record TextExport routes to
                                         .DLSTRINGS (MISMATCH demo)
"""

import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "STRINGS")


def build(kind, records):
    """Return the full compiled file bytes for one kind.

    ``records`` is a list of (stringID, text-bytes). Rows are emitted sorted
    ascending by ID; the data block is laid out in that same order, so every
    table offset lands on a record boundary and the block walks to EOF.
    """
    records = sorted(records)
    data = bytearray()
    offsets = []
    for _sid, text in records:
        offsets.append(len(data))
        if kind == ".STRINGS":
            data += text + b"\x00"
        else:
            data += struct.pack("<I", len(text) + 1) + text + b"\x00"
    header = struct.pack("<II", len(records), len(data))
    table = b"".join(struct.pack("<II", sid, off)
                     for (sid, _text), off in zip(records, offsets))
    return header + table + bytes(data)


SPECS = {
    ".STRINGS": [
        (0x12, b"topic line"),
        (0x13, b"response line"),
    ],
    ".DLSTRINGS": [
        (0x10, b"stage entry"),
        (0x36, b"paint description"),
    ],
    ".ILSTRINGS": [
        (0x126C5, b"supp paint a"),
        (0x126C6, b"supp paint b"),
    ],
}


def main():
    os.makedirs(OUT, exist_ok=True)
    for kind, records in SPECS.items():
        path = os.path.join(OUT, "Fallout4_en" + kind)
        with open(path, "wb") as fh:
            fh.write(build(kind, records))
        print("wrote %s (%d bytes)" % (path, os.path.getsize(path)))


if __name__ == "__main__":
    main()
