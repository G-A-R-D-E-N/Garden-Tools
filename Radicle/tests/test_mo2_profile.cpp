namespace {

std::string wine_z(const std::filesystem::path& host) {
  auto text = "Z:" + host.generic_string();
  std::replace(text.begin(), text.end(), '/', '\\');
  return text;
}

std::string ini_escaped(const std::string& text) {
  std::string out;
  for (const char ch : text) {
    out += ch;
    if (ch == '\\') out += '\\';
  }
  return out;
}

class ScopedEnv {
public:
  ScopedEnv(const char* name, const char* value) : name_{name} {
    if (const char* old = std::getenv(name)) old_ = old;
    had_ = std::getenv(name) != nullptr;
    if (value != nullptr) setenv(name, value, 1);
    else unsetenv(name);
  }
  ~ScopedEnv() {
    if (had_) setenv(name_, old_.c_str(), 1);
    else unsetenv(name_);
  }
  ScopedEnv(const ScopedEnv&) = delete;
  ScopedEnv& operator=(const ScopedEnv&) = delete;

private:
  const char* name_;
  std::string old_;
  bool had_ = false;
};

}  // namespace

TEST(Mo2WinePath, OtherDriveResolvesThroughThePrefixDosdevicesLinkWithCaseFallback) {
  TempDataDir root;
  write_text(root.path() / "games" / "Fallout 4" / "Data" / "Fallout4.esm", "");
  std::filesystem::create_directories(root.path() / "pfx" / "dosdevices");
  std::error_code ec;
  std::filesystem::create_directory_symlink(root.path() / "games", root.path() / "pfx" / "dosdevices" / "d:", ec);
  if (ec) GTEST_SKIP() << "directory symlinks are not available: " << ec.message();

  const auto exact = mo2_wine_native_path("D:\\Fallout 4\\Data", root.path() / "pfx", "/unused");
  EXPECT_EQ(exact, root.path() / "pfx" / "dosdevices" / "d:" / "Fallout 4" / "Data");
  EXPECT_TRUE(same_place(exact, root.path() / "games" / "Fallout 4" / "Data")) << exact;

  const auto shouted = mo2_wine_native_path("d:\\FALLOUT 4\\DATA", root.path() / "pfx", "/unused");
  EXPECT_TRUE(same_place(shouted, root.path() / "games" / "Fallout 4" / "Data")) << shouted;

  EXPECT_EQ(mo2_wine_native_path("E:\\Elsewhere", root.path() / "pfx", "/unused"),
            std::filesystem::path("E:/Elsewhere"));
}

