#!/usr/bin/env python3
"""Generate the global FormLink tables from schema/fallout4/fields.json.

formid_subrecords: four-byte FormID subrecords by signature.
structured_formids: FormID slots inside mixed-type subrecords (signature, offset, min_size).
unclaimed_link_allowlist: (record, subrecord) pairs exempt from the unclaimed-payload report.
"""
import argparse
import json
import sys
from pathlib import Path

HEADER = ("// Generated by Radicle/tools/form_link_tables_codegen.py from schema/fallout4/fields.json.\n"
          "// Do not hand-edit; update the JSON source and regenerate.\n")


def valid_signature(value) -> bool:
    return isinstance(value, str) and len(value) == 4 and all(0x20 <= ord(ch) <= 0x7E for ch in value)


def packed(signature: str) -> int:
    return int.from_bytes(signature.encode("ascii"), "little")


def collect(document):
    subrecords = document.get("formid_subrecords")
    structured = document.get("structured_formids")
    allowlist = document.get("unclaimed_link_allowlist")
    if not isinstance(subrecords, list) or not isinstance(structured, list) or not isinstance(allowlist, list):
        raise ValueError("fields.json must declare formid_subrecords, structured_formids and unclaimed_link_allowlist")
    seen = set()
    for signature in subrecords:
        if not valid_signature(signature):
            raise ValueError(f"invalid formid_subrecords signature: {signature!r}")
        if signature in seen:
            raise ValueError(f"duplicate formid_subrecords signature: {signature}")
        seen.add(signature)
    seen_slots = set()
    for row in structured:
        signature, offset, min_size = row.get("signature"), row.get("offset"), row.get("min_size")
        if not valid_signature(signature):
            raise ValueError(f"invalid structured_formids signature: {signature!r}")
        if type(offset) is not int or type(min_size) is not int or offset < 0 or min_size < offset + 4 or min_size > 0xFFFF:
            raise ValueError(f"invalid structured_formids slot for {signature}: offset {offset!r}, min_size {min_size!r}")
        if (signature, offset) in seen_slots:
            raise ValueError(f"duplicate structured_formids slot: {signature} at {offset}")
        seen_slots.add((signature, offset))
        note = row.get("note", "")
        if not isinstance(note, str) or "\n" in note:
            raise ValueError(f"structured_formids note must be one line: {signature} at {offset}")
    seen_pairs = set()
    for pair in allowlist:
        if not (isinstance(pair, list) and len(pair) == 2 and all(valid_signature(item) for item in pair)):
            raise ValueError(f"invalid unclaimed_link_allowlist pair: {pair!r}")
        if tuple(pair) in seen_pairs:
            raise ValueError(f"duplicate unclaimed_link_allowlist pair: {pair}")
        seen_pairs.add(tuple(pair))
    return subrecords, structured, allowlist


def render(subrecords, structured, allowlist):
    files = {}
    files["formid_subrecords.inc"] = HEADER + "".join(
        f"0x{packed(signature):08X}u,  // {signature}\n" for signature in subrecords)
    lines = [HEADER]
    for row in structured:
        if row.get("note"):
            lines.append(f"// {row['note']}\n")
        lines.append(f"{{0x{packed(row['signature']):08X}u, {row['offset']}, {row['min_size']}}},  // {row['signature']}\n")
    files["structured_formids.inc"] = "".join(lines)
    files["unclaimed_link_allowlist.inc"] = HEADER + "".join(
        f'{{"{record}", "{subrecord}"}},\n' for record, subrecord in allowlist)
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    document = json.loads(Path(args.schema).read_text(encoding="utf-8"))
    files = render(*collect(document))
    directory = Path(args.output_dir)

    if args.check:
        stale = [name for name, text in files.items()
                 if not (directory / name).exists()
                 or (directory / name).read_text(encoding="utf-8") != text]
        for name in stale:
            sys.stderr.write(f"{directory / name} is stale; regenerate with form_link_tables_codegen.py\n")
        return 1 if stale else 0

    directory.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        with open(directory / name, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
