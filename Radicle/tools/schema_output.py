"""Sharded output for the generated Fallout 4 scalar field table."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import schema_codegen  # noqa: E402


SHARD_ROW_BUDGET = 500


def shard_rows(rows, budget=SHARD_ROW_BUDGET):
    shards = []
    current = []
    previous = None
    for key, line in rows:
        if current and key != previous and len(current) >= budget:
            shards.append(current)
            current = []
        current.append((key, line))
        previous = key
    if current:
        shards.append(current)
    return shards


def split_rows(fields, text: str):
    lines = text.split("\n")
    start = lines.index("constexpr ScalarFieldDescriptor k_scalar_fields[] = {") + 1
    end = lines.index("};", start)
    rows = lines[start:end]
    if len(rows) != len(fields):
        raise ValueError(f"scalar table has {len(rows)} rows for {len(fields)} fields")
    return lines[:start], [(field["record"], row) for field, row in zip(fields, rows)], lines[end:]


def render_output(fields, arrays, groups, output: Path):
    head, rows, tail = split_rows(fields, schema_codegen.render(fields, arrays, groups))
    shards = shard_rows(rows)
    names = [f"{output.stem}_{index + 1}.inc" for index in range(len(shards))]
    header = ("// Generated by Radicle/tools/schema_codegen.py from schema/fallout4/fields.json.\n"
              "// Do not hand-edit; update the JSON source and regenerate.\n")
    files = {output: "\n".join(head + [f'#include "{name}"' for name in names] + tail)}
    for name, shard in zip(names, shards):
        files[output.parent / name] = (header + f"// Records {shard[0][0]} to {shard[-1][0]}.\n"
                                       + "\n".join(line for _key, line in shard) + "\n")
    return files


def stale_shard_files(files, output: Path):
    produced = {path.name for path in files}
    return sorted(path for path in output.parent.glob(f"{output.stem}_[0-9]*.inc")
                  if path.name not in produced)


def emit(fields, arrays, groups, output: Path, check: bool) -> int:
    files = render_output(fields, arrays, groups, output)
    if not check:
        write_files(files, output)
        return 0
    stale = [path for path, text in files.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    stale.extend(stale_shard_files(files, output))
    for path in stale:
        print(f"generated schema is stale: {path}")
    return 1 if stale else 0


def write_files(files, output: Path):
    output.parent.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    for path in stale_shard_files(files, output):
        path.unlink()
