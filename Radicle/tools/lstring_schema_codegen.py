#!/usr/bin/env python3
"""Generate the localized-subrecord table from schema/fallout4/fields.json.

A localized plugin stores these subrecords as a four-byte string ID into the
.STRINGS tables rather than as inline text. Which fields those are cannot be
inferred from payload size -- NPC_ CNAM is four bytes but is a Class FormID --
so the set is declared per (record, subrecord) pair in the schema.
"""
import argparse
import json
import sys


def cpp_string(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def collect(schema):
    out = []
    for record in schema["records"]:
        for subrecord in record.get("localized_subrecords", []):
            out.append((record["signature"], subrecord))
    out.sort()
    return out


def render(pairs) -> str:
    lines = [
        "// Generated by Radicle/tools/lstring_schema_codegen.py from schema/fallout4/fields.json.",
        "// Do not hand-edit; update the JSON source and regenerate.",
        "inline constexpr LocalizedFieldEntry k_generated_localized_fields[] = {",
    ]
    for record, subrecord in pairs:
        lines.append(
            "  {"
            + f"Signature::from_string({cpp_string(record)}), "
            + f"Signature::from_string({cpp_string(subrecord)})"
            + "},"
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    with open(args.schema, encoding="utf-8") as handle:
        rendered = render(collect(json.load(handle)))

    if args.check:
        try:
            with open(args.output, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = None
        if current != rendered:
            sys.stderr.write(
                f"{args.output} is stale; regenerate with lstring_schema_codegen.py\n")
            return 1
        return 0

    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
