def fail(message):
    raise SystemExit(message)


def load_signatures():
    sigs = {}
    for line in SIGNATURES.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        sig, line_no = line.split()
        if sig in sigs:
            fail(f"duplicate {sig}")
        sigs[sig] = int(line_no)
    return sigs


def mixed_record_signatures(text):
    constants = dict(re.findall(r'constexpr auto k_(\w+) = Signature::from_string\("(\w{4})"\);', text))
    found = set(re.findall(r'"([A-Z][A-Z0-9_]{3})"', text))
    found |= {name.upper() for name in re.findall(r"\bsig_(\w{4})\b", text)}
    found |= {constants[name] for name in re.findall(r"\bk_(\w+)\b", text) if name in constants}
    return found


def typed_modules(sigs):
    found = {}
    for path, names in TYPED_MODULES.items():
        text = (ROOT / path).read_text(encoding="utf-8")
        for name in names:
            if name not in sigs:
                fail(f"{path}: {name} is not in xedit_signatures.txt")
            if not (f'"{name}"' in text or f"sig_{name.lower()}" in text or f"k_{name.lower()}" in text):
                fail(f"{path}: does not name {name}")
            found.setdefault(name, []).append(path)
    return found


def real_test_sources():
    names = sorted(set(re.findall(r"tests/\w+_real\.cpp", CMAKE.read_text(encoding="utf-8"))))
    return [(ROOT / name).read_text(encoding="utf-8") for name in names]


def short_module(path):
    return path.removeprefix("src/").removesuffix(".cpp")


def cell(value):
    return str(value) if value else "-"


def tier_of(scalar, string, formlink, authoring, modules, lists, keyword):
    if scalar or string or formlink or authoring:
        return "L4"
    if lists:
        return "L3"
    if modules:
        return "L2"
    if keyword:
        return "L1"
    return "L0"


def tier_summary(tiers, authoring_only, listed):
    summary = ", ".join(f"{tier} {tiers.get(tier, 0)}" for tier in ["L0", "L1", "L2", "L3", "L4"])
    if not authoring_only:
        return summary
    extra = f"; FormLink list rows are also present on {', '.join(listed)}" if listed else ""
    return (f"{summary} ({len(authoring_only)} L4 rows have an authoring constraint and no scalar, string "
            f"or FormLink field rows: {', '.join(authoring_only)}{extra})")


def scalar_rows(record_signature, rows):
    expanded = []
    for row in rows:
        if row.get("kind") == "counted_array":
            expanded.extend(schema_codegen.parse_counted_array(row, record_signature)[1])
        elif row.get("kind") == "subrecord_group":
            expanded.extend(schema_codegen.parse_subrecord_group(row, record_signature)[1])
        else:
            expanded.append(row)
    return expanded


def formlink_rows(record_signature, record):
    rows = list(record.get("formlink_fields", []))
    for row in record.get("fields", []):
        if row.get("kind") == "subrecord_group":
            rows.extend(schema_codegen.parse_subrecord_group(row, record_signature)[2])
    return rows


def render():
    sigs = load_signatures()
    data = json.loads(FIELDS.read_text(encoding="utf-8"))
    records = {record["signature"]: record for record in data["records"]}
    keywords = {entry["record"] for entry in data["keyword_records"]}
    unknown = (set(records) | keywords) - set(sigs)
    if unknown:
        fail(f"fields.json names signatures outside xedit_signatures.txt: {sorted(unknown)}")
    modules = typed_modules(set(sigs))
    mixed = (mixed_record_signatures(MIXED.read_text(encoding="utf-8"))
             | mixed_record_signatures(MIXED_RECORDS.read_text(encoding="utf-8"))) & set(sigs)
    real_texts = real_test_sources()

    main_rows = []
    tiers = {}
    authoring_only = []
    authoring_only_lists = []
    for sig in sorted(sigs):
        record = records.get(sig, {})
        rows = scalar_rows(sig, record.get("fields", []))
        scalar = sum(row["kind"] == "scalar" for row in rows)
        string = sum(row["kind"] == "string" for row in rows)
        formlink = len(formlink_rows(sig, record))
        lists = len(record.get("formlink_lists", [])) + len(record.get("nested_formlink_lists", []))
        localized = len(record.get("localized_subrecords", []))
        authoring = "authoring" in record
        keyword = sig in keywords
        typed = [short_module(path) for path in modules.get(sig, [])]
        real = sum(f'"{sig}"' in text for text in real_texts)
        tier = tier_of(scalar, string, formlink, authoring, typed, lists, keyword)
        tiers[tier] = tiers.get(tier, 0) + 1
        if tier == "L4" and authoring and not scalar and not string and not formlink:
            authoring_only.append(sig)
            if lists:
                authoring_only_lists.append(sig)
        main_rows.append(
            f"| {sig} | {sigs[sig]} | {cell(scalar)} | {cell(string)} | {cell(formlink)} | {cell(lists)} | "
            f"{cell(localized)} | {'yes' if authoring else '-'} | {'yes' if keyword else '-'} | "
            f"{', '.join(typed) or '-'} | {'yes' if sig in mixed else '-'} | {cell(real)} | {tier} |"
        )

    kind_rows = []
    for sig in sorted(records):
        rows = scalar_rows(sig, records[sig]["fields"])
        addressed = rows + formlink_rows(sig, records[sig])
        identity = sum(row["kind"] == "scalar" and row.get("presentation") == "identity" for row in rows)
        percent = sum(row.get("presentation") == "percent_0_100" for row in rows)
        enum = sum(row["kind"] == "scalar" and row.get("presentation") == "enum" for row in rows)
        flags = sum(row["kind"] == "scalar" and row.get("presentation") == "flags" for row in rows)
        strings = sum(row["kind"] == "string" for row in rows)
        storage = ", ".join(sorted({row["storage"] for row in rows if row["kind"] == "scalar"})) or "-"
        repeated = sum(bool(row.get("repeated")) for row in addressed)
        stride = sum("stride" in row for row in addressed)
        when = sum("when" in row for row in addressed)
        insertion = ", ".join(sorted({row["insertion"] for row in addressed})) or "-"
        kind_rows.append(
            f"| {sig} | {cell(identity)} | {cell(percent)} | {cell(enum)} | {cell(flags)} | {cell(strings)} | {storage} | "
            f"{cell(repeated)} | {cell(stride)} | {cell(when)} | {insertion} |"
        )

    tier_line = tier_summary(tiers, authoring_only, authoring_only_lists)
    lines = [
        BEGIN,
        "",
        f"Derived from the repository by `Radicle/tools/parity_matrix.py`; {len(sigs)} signatures from `schema/fallout4/xedit_signatures.txt`. Regenerate with `python -I Radicle/tools/parity_matrix.py --write`.",
        "",
        "Columns: xEdit line is the registration line in the pinned definitions. Rows, authoring, keyword list and FormLink counts come from `schema/fallout4/fields.json`. Scalar rows counts only rows whose kind is `scalar` and String rows only `string`, while the generated `k_scalar_fields` table and `schema::scalar_fields()` carry both, so a record's row-table size is Scalar rows plus String rows - a record with one string row reports one less in the Scalar column than `scalar_fields()` returns for it. Typed module lists the `TYPED_MODULES` files that name the signature. Mixed remap means the signature is named in `src/schema/form_link_mixed.cpp` or `src/schema/form_link_records.cpp`. Real-data tests count registered `tests/*_real.cpp` files that name it. `-` means none.",
        "",
        "Tier: L4 has field rows, FormLink fields or authoring constraints; L2 has a typed module, no rows or lists; L3 has FormLink list rows only; L1 has a keyword list only; L0 has none of these. A record with an authoring constraint but no scalar, string or FormLink field rows is still L4, and the tier counts break those out. Remap evidence (the Mixed remap column and the form_links.cpp record checks) does not affect the tier. L5 (dedicated PET route) is not derived.",
        "",
        f"Tier counts: {tier_line}.",
        "",
        "### Per-signature coverage",
        "",
        "| Record | xEdit line | Scalar rows | String rows | FormLink fields | FormLink lists | Localized subrecords | Authoring | Keyword list | Typed module | Mixed remap | Real-data tests naming it | Tier |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- | --- | --- | ---: | --- |",
        *main_rows,
        "",
        "### Field-kind coverage",
        "",
        "Rows listed in `fields.json` only. Scalar storage and presentation come from scalar rows; addressing counts include FormLink fields.",
        "",
        "| Record | Scalar identity | Scalar percent_0_100 | Scalar enum | Scalar flags | String | Scalar storage | Repeated | Stride | When | Insertion |",
        "| --- | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: | ---: | --- |",
        *kind_rows,
        "",
        "### Unsupported or opaque (not attributable by the script)",
        "",
        *[f"- {note}" for note in OPAQUE_NOTES],
        END,
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    block = render()
    if not (args.write or args.check):
        sys.stdout.write(block + "\n")
        return 0
    text = DOC.read_text(encoding="utf-8")
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < start:
        fail(f"{DOC.name} is missing the parity-matrix markers")
    updated = text[:start] + block + text[end + len(END):]
    if args.check:
        if updated != text:
            print(f"{DOC.name} parity matrix is stale; run python -I Radicle/tools/parity_matrix.py --write")
            return 1
        return 0
    with DOC.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(updated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
