#!/usr/bin/env python3

import argparse
import json
from pathlib import Path


def valid_signature(value: str) -> bool:
    return len(value) == 4 and all(0x20 <= ord(ch) <= 0x7E for ch in value)


def cpp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


SCOPE_KINDS = {"effect", "alias", "package_branch", "quest_target", "perk_effect_tab",
               "message_button", "terminal_body_text", "terminal_menu_item"}


def valid_token(value: str) -> bool:
    return (
        isinstance(value, str)
        and bool(value)
        and "\\" not in value
        and "[" not in value
        and "]" not in value
        and "." not in value
        and all(ord(ch) >= 0x20 for ch in value)
    )


def load_scopes(schema_path: Path):
    document = json.loads(schema_path.read_text(encoding="utf-8"))
    if document.get("version") != 1:
        raise ValueError("unsupported Fallout 4 field schema version")

    scopes = document.get("condition_scopes", [])
    if not isinstance(scopes, list):
        raise ValueError("condition_scopes must be an array")

    parsed = []
    seen = set()
    for entry in scopes:
        if not isinstance(entry, dict):
            raise ValueError("condition_scopes entries must be objects")
        record = entry.get("record", "")
        container = entry.get("container", "")
        member = entry.get("member", "")
        scope = entry.get("scope", "")
        if not isinstance(record, str) or not valid_signature(record):
            raise ValueError(f"condition scope record signature must be four printable ASCII characters: {record!r}")
        if not valid_token(container):
            raise ValueError(f"condition scope container is invalid: {container!r}")
        if not valid_token(member):
            raise ValueError(f"condition scope member is invalid: {member!r}")
        if scope not in SCOPE_KINDS:
            raise ValueError(f"unsupported condition scope kind: {scope!r}")
        key = (record, container, member)
        if key in seen:
            raise ValueError(f"duplicate condition scope: {record}\\{container}\\{member}")
        seen.add(key)
        parsed.append({
            "record": record,
            "container": container,
            "member": member,
            "scope": scope,
        })

    parsed.sort(key=lambda item: (item["record"], item["container"], item["member"]))
    return parsed


def render(scopes) -> str:
    lines = [
        "// Generated by Radicle/tools/condition_scope_codegen.py from schema/fallout4/fields.json.",
        "// Do not hand-edit; update the JSON source and regenerate.",
        "inline constexpr ConditionScopeDescriptor k_generated_condition_scopes[] = {",
    ]
    for row in scopes:
        lines.append(
            "  {" +
            f"Signature::from_string({cpp_string(row['record'])}), " +
            f"{cpp_string(row['container'])}, {cpp_string(row['member'])}, " +
            f"ConditionScopeKind::{row['scope']}" +
            "},"
        )
    if not scopes:
        lines.append("  {Signature{}, \"\", \"\", ConditionScopeKind::effect},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    scopes = load_scopes(args.schema)
    expected = render(scopes)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != expected:
            print(f"generated condition scope schema is stale: {args.output}")
            return 1
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
