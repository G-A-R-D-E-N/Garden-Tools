#include "fo4/environment/environment.hpp"
#include "fo4/previs/detect.hpp"
#include "fo4/previs/previs_data.hpp"

#include <algorithm>
#include <cstddef>
#include <exception>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

namespace fs = std::filesystem;

namespace {

std::string issue_codes(const fo4::previs::CellPrevisStatus& status) {
  std::vector<std::string> codes;
  for (const auto& issue : status.issues) codes.emplace_back(fo4::previs::to_string(issue.code));
  std::sort(codes.begin(), codes.end());
  std::string joined;
  for (std::size_t i = 0; i < codes.size(); ++i) {
    if (i != 0) joined.push_back(',');
    joined += codes[i];
  }
  return joined;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc != 4) {
    std::cerr << "usage: vanilla_broken_tsv <Fallout 4 Data folder> <out.tsv> <build, e.g. 1.11.240.0>\n";
    return 2;
  }
  try {
    const fs::path data = argv[1];
    const std::vector<std::string> names{"Fallout4.esm",   "DLCRobot.esm",      "DLCworkshop01.esm",
                                         "DLCCoast.esm",   "DLCworkshop03.esm", "DLCNukaWorld.esm"};
    std::vector<fs::path> masters;
    for (const auto& name : names) {
      if (!fs::is_regular_file(data / name)) {
        std::cerr << "missing master " << (data / name).string() << "\n";
        return 1;
      }
      masters.push_back(data / name);
    }
    const auto env = fo4::env::Environment::load(masters);
    const fs::path roots[]{data};
    const auto previs = fo4::previs::PrevisData::load(roots, env);
    if (!previs.summary().problems.empty()) {
      for (const auto& problem : previs.summary().problems) std::cerr << "scan problem: " << problem << "\n";
      return 1;
    }
    const auto report = fo4::previs::diagnose_load_order(env, previs.indexes());

    std::ofstream out(argv[2], std::ios::binary | std::ios::trunc);
    if (!out) {
      std::cerr << "cannot write " << argv[2] << "\n";
      return 1;
    }
    out << "# Generated by Radicle/tools/previs/vanilla_broken_tsv from the Fallout 4 AE " << argv[3]
        << " Data folder; do not edit by hand.\n";
    std::size_t broken = 0;
    for (const auto& diagnosis : report) {
      if (!diagnosis.status.broken) continue;
      ++broken;
      out << diagnosis.cell.to_string() << '\t' << issue_codes(diagnosis.status) << '\n';
    }
    out.close();
    if (!out) {
      std::cerr << "write failed for " << argv[2] << "\n";
      return 1;
    }
    std::cout << report.size() << " cells, " << broken << " broken, written to " << argv[2] << "\n";
    return 0;
  } catch (const std::exception& error) {
    std::cerr << "failed: " << error.what() << "\n";
    return 1;
  }
}
