#!/usr/bin/env python3

import argparse
import json
from pathlib import Path

BS = chr(92)
ENTRY_KEYS = {"path", "label", "bit"}


def valid_signature(value: str) -> bool:
    return len(value) == 4 and all(0x20 <= ord(ch) <= 0x7E for ch in value)


def parse_flags(record_signature: str, entries, seen_paths):
    if not isinstance(entries, list) or not entries:
        raise ValueError(f"record_flags must be a non-empty array: {record_signature}")
    rows = []
    seen_bits = set()
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != ENTRY_KEYS:
            raise ValueError(f"record_flags entries need exactly {sorted(ENTRY_KEYS)}: {record_signature}")
        path, label, bit = entry["path"], entry["label"], entry["bit"]
        if not isinstance(path, str) or not path.startswith(record_signature + BS):
            raise ValueError(f"record_flags path must be qualified by {record_signature}{BS}: {path!r}")
        if not isinstance(label, str) or not label or any(not 0x20 <= ord(ch) <= 0x7E for ch in label):
            raise ValueError(f"record_flags label must be non-empty printable ASCII: {path!r}")
        if type(bit) is not int or not 0 <= bit < 32:
            raise ValueError(f"record_flags bit must be an integer below 32: {path!r}")
        if bit in seen_bits:
            raise ValueError(f"duplicate record_flags bit {bit}: {record_signature}")
        seen_bits.add(bit)
        if path in seen_paths:
            raise ValueError(f"duplicate record_flags path: {path!r}")
        seen_paths.add(path)
        rows.append({"record": record_signature, "path": path, "label": label, "bit": bit, "mask": 1 << bit})
    return rows


def load_rows(schema_path: Path):
    document = json.loads(schema_path.read_text(encoding="utf-8"))
    if document.get("version") != 1:
        raise ValueError("unsupported Fallout 4 field schema version")
    records = document.get("records")
    if not isinstance(records, list):
        raise ValueError("schema records must be an array")

    rows = []
    seen_paths = set()
    seen_records = set()
    for record in records:
        if not isinstance(record, dict):
            raise ValueError("schema record entries must be objects")
        signature = record.get("signature", "")
        if not isinstance(signature, str) or not valid_signature(signature):
            raise ValueError(f"record signature must be four printable ASCII characters: {signature!r}")
        if "record_flags" not in record:
            continue
        if signature in seen_records:
            raise ValueError(f"duplicate record_flags record: {signature}")
        seen_records.add(signature)
        rows.extend(parse_flags(signature, record["record_flags"], seen_paths))
    rows.sort(key=lambda row: (row["record"], row["bit"]))
    return rows


def render(rows) -> str:
    body = "\n".join(
        f'{{Signature::from_string({json.dumps(row["record"])}), {json.dumps(row["path"])}, '
        f'{json.dumps(row["label"])}, 0x{row["mask"]:08x}u}},' for row in rows)
    return ("// Generated by Radicle/tools/record_flag_codegen.py from schema/fallout4/fields.json.\n"
            "// Do not hand-edit; update the JSON source and regenerate.\n"
            "constexpr RecordFlagDescriptor k_record_flags[] = {\n" + body + "\n};\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = render(load_rows(args.schema))
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
            print(f"generated schema is stale: {args.output}")
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
