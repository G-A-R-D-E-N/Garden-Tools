#!/usr/bin/env python3
"""Generate the Havok class layout table from BGS's measured class JSON.

Member offsets and instance sizes come from HavokClassLayouts.json; class signatures come
from HavokClassTypes.json. Only classes present in both files are emitted, so every row
carries the signature that find_layout checks against the signature in a packfile.
"""
import argparse
import json
import re
import sys

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
SIGNATURE = re.compile(r"^0x[0-9a-f]{8}$")


def cpp_string(value: str) -> str:
    if not all(0x20 <= ord(ch) <= 0x7E for ch in value):
        raise ValueError(f"non-ASCII name {value!r}")
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def collect(layouts, types):
    rows = []
    for name in sorted(layouts):
        if name not in types:
            continue
        if not IDENT.match(name):
            raise ValueError(f"class name {name!r} is not a C identifier")
        signature = types[name].get("signature")
        if not isinstance(signature, str) or not SIGNATURE.match(signature):
            raise ValueError(f"{name} has no signature of the form 0x + 8 lowercase hex digits")
        entry = layouts[name]
        members = []
        for member in entry["members"]:
            member_name, offset = member[0], member[1]
            if not isinstance(offset, int) or offset < 0:
                raise ValueError(f"{name}.{member_name} has offset {offset!r}")
            members.append((member_name, offset))
        rows.append((name, signature, int(entry["size"]), members))
    return rows


def render(rows) -> str:
    lines = [
        "// Generated by Radicle/tools/hkx_layout_codegen.py from BGS/src/Hkx/HavokClassLayouts.json",
        "// and BGS/src/Hkx/HavokClassTypes.json. Do not hand-edit; update the JSON source and regenerate.",
    ]
    for name, _, _, members in rows:
        if members:
            body = ", ".join("{" + cpp_string(member_name) + f", {offset}u" + "}" for member_name, offset in members)
            lines.append(f"inline constexpr HkxMemberLayout k_members_{name}[] = {{{body}}};")
    lines.append("inline constexpr HkxClassLayout k_hkx_classes[] = {")
    for name, signature, size, members in rows:
        table = f"k_members_{name}" if members else "{}"
        lines.append(
            "  {"
            + f"{cpp_string(name)}, {int(signature, 16)}u, {size}u, {table}"
            + "},"
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--layouts", required=True)
    parser.add_argument("--types", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    with open(args.layouts, encoding="utf-8") as handle:
        layouts = json.load(handle)["classes"]
    with open(args.types, encoding="utf-8") as handle:
        types = json.load(handle)["classes"]
    rendered = render(collect(layouts, types))

    if args.check:
        try:
            with open(args.output, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = None
        if current != rendered:
            sys.stderr.write(
                f"{args.output} is stale; regenerate with hkx_layout_codegen.py\n")
            return 1
        return 0

    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
