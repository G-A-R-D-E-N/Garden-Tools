std::vector<std::byte> encode_ragdoll_constraint(const HknpConstraint& constraint) {
  auto out = from_template(k_ragdoll_template);
  put_frames(out, constraint);
  put_flag(out, 0xB2, constraint.setup_stabilization);
  put_flag(out, 0xC2, constraint.motor_enabled);
  put_f32(out, 0x128, constraint.friction);
  put_limit(out, 0x138, 0x13C, 0x140, constraint.twist);
  put_limit(out, 0x158, 0x15C, 0x160, constraint.cone);
  put_limit(out, 0x178, 0x17C, 0x180, constraint.plane);
  put_u8(out, 0x192, constraint.ball_socket_method);
  return out;
}

std::vector<std::byte> encode_limited_hinge_constraint(const HknpConstraint& constraint) {
  auto out = from_template(k_limited_hinge_template);
  put_frames(out, constraint);
  put_flag(out, 0xB2, constraint.setup_stabilization);
  put_flag(out, 0xC2, constraint.motor_enabled);
  put_f32(out, 0xF0, constraint.friction);
  put_limit(out, 0xFC, 0x100, 0x104, constraint.hinge);
  put_u8(out, 0x11A, constraint.ball_socket_method);
  return out;
}

std::vector<std::byte> encode_ball_and_socket_constraint(const HknpConstraint& constraint) {
  auto out = from_template(k_ball_and_socket_template);
  put_vec4(out, 0x30, constraint.translation_a);
  put_vec4(out, 0x40, constraint.translation_b);
  put_flag(out, 0x52, constraint.setup_stabilization);
  put_u8(out, 0x62, constraint.ball_socket_method);
  return out;
}

std::vector<std::byte> encode_prismatic_constraint(const HknpConstraint& constraint) {
  auto out = from_template(k_prismatic_template);
  put_frames(out, constraint);
  put_flag(out, 0xB2, constraint.linear_motor_enabled);
  put_f32(out, 0x10C, constraint.linear_limit.min);
  put_f32(out, 0x110, constraint.linear_limit.max);
  return out;
}

std::vector<std::byte> encode_breakable_constraint(const HknpConstraint& constraint) {
  auto out = from_template(k_breakable_template);
  put_f32(out, 0x20, constraint.break_threshold);
  return out;
}

std::vector<std::byte> encode_position_motor(const HknpPositionMotor& motor) {
  auto out = from_template(k_position_motor_template);
  put_f32(out, 32, motor.tau);
  put_f32(out, 36, motor.damping);
  put_f32(out, 40, motor.proportional_recovery_velocity);
  put_f32(out, 44, motor.constant_recovery_velocity);
  return out;
}

