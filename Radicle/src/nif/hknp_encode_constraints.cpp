template <std::size_t N>
std::vector<std::byte> from_template(const std::array<std::uint8_t, N>& templ) {
  std::vector<std::byte> out(N);
  for (std::size_t i = 0; i < N; ++i) out[i] = std::byte{templ[i]};
  return out;
}

void put_u8(std::vector<std::byte>& out, std::size_t at, std::uint8_t value) {
  out[at] = std::byte{value};
}

void put_flag(std::vector<std::byte>& out, std::size_t at, bool value) {
  put_u8(out, at, static_cast<std::uint8_t>(value ? 1 : 0));
}

void put_f32(std::vector<std::byte>& out, std::size_t at, float value) {
  std::uint32_t bits = 0;
  std::memcpy(&bits, &value, sizeof bits);
  for (std::size_t i = 0; i < 4; ++i) out[at + i] = static_cast<std::byte>((bits >> (8 * i)) & 0xFFu);
}

void put_vec4(std::vector<std::byte>& out, std::size_t at, const HknpVec4& value) {
  for (std::size_t k = 0; k < 4; ++k) put_f32(out, at + 4 * k, value[k]);
}

void put_frames(std::vector<std::byte>& out, const HknpConstraint& constraint) {
  for (std::size_t k = 0; k < 3; ++k) {
    put_vec4(out, 0x30 + 16 * k, constraint.frame_a[k]);
    put_vec4(out, 0x70 + 16 * k, constraint.frame_b[k]);
  }
  put_vec4(out, 0x60, constraint.frame_a[3]);
  put_vec4(out, 0xA0, constraint.frame_b[3]);
}

void put_limit(std::vector<std::byte>& out, std::size_t min_at, std::size_t max_at, std::size_t tau_at,
               const HknpAngularLimit& limit) {
  put_f32(out, min_at, limit.min);
  put_f32(out, max_at, limit.max);
  put_f32(out, tau_at, limit.tau);
}

